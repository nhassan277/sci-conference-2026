CREATE TABLE `media_registrations` (
	`id` int AUTO_INCREMENT NOT NULL,
	`conference_name` varchar(255) NOT NULL DEFAULT 'SCI 2026',
	`conference_date` varchar(100) NOT NULL DEFAULT 'April 7-8, 2026',
	`conference_location` varchar(255) NOT NULL DEFAULT 'Faculty of Science, Cairo University',
	`organization_name` varchar(255) NOT NULL,
	`organization_type` varchar(50) NOT NULL,
	`coverage_type` varchar(50) NOT NULL,
	`full_name` varchar(255) NOT NULL,
	`job_title` varchar(255) NOT NULL,
	`phone` varchar(50) NOT NULL,
	`email` varchar(255) NOT NULL,
	`press_card_number` varchar(100),
	`team_members` json,
	`status` varchar(50) NOT NULL DEFAULT 'pending',
	`approved_by` varchar(255),
	`approved_at` timestamp,
	`rejection_reason` text,
	`badge_issued` boolean NOT NULL DEFAULT false,
	`badge_issued_at` timestamp,
	`badge_number` varchar(50),
	`agreement_accepted` boolean NOT NULL DEFAULT true,
	`ip_address` varchar(50),
	`user_agent` text,
	`notes` text,
	`created_at` timestamp NOT NULL DEFAULT (now()),
	`updated_at` timestamp NOT NULL DEFAULT (now()) ON UPDATE CURRENT_TIMESTAMP,
	CONSTRAINT `media_registrations_id` PRIMARY KEY(`id`)
);
